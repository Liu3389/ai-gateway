-- ============================================
-- 限流Lua脚本（基于滑动窗口的计数器算法）
-- ============================================
-- 功能说明：
--   实现基于Redis的API请求限流功能，防止单个API Key过度使用系统资源
--   采用固定时间窗口算法，在指定的时间窗口内限制请求数量
--
-- 算法原理：
--   1. 为每个API Key维护一个计数器
--   2. 计数器在固定的时间窗口内累加请求次数
--   3. 当请求次数超过阈值时，拒绝后续请求
--   4. 时间窗口结束后，计数器自动过期重置
--
-- 性能优势：
--   - 使用Lua脚本保证原子性操作，避免竞态条件
--   - 直接在Redis服务器执行，减少网络往返
--   - 时间复杂度O(1)，高性能限流
--
-- 参数说明：
--   KEYS[1]: 限流Key，格式为 ai_gateway:rate_limit:{apiKey}
--            用于唯一标识某个API Key的限流计数器
--   ARGV[1]: 限流阈值，表示每分钟允许的最大请求数
--            例如：100表示每分钟最多100次请求
--   ARGV[2]: 当前时间戳（秒），用于调试和日志记录
--   ARGV[3]: 时间窗口大小（秒），通常为60秒（1分钟）
--            计数器在此时间后自动过期
--
-- 返回值说明：
--   1 - 请求允许，未超过限流阈值
--   0 - 请求拒绝，已超过限流阈值
-- ============================================

-- 获取传入的参数
local key = KEYS[1]              -- 限流Key
local limit = tonumber(ARGV[1])  -- 限流阈值（转换为数字类型）
local now = tonumber(ARGV[2])    -- 当前时间戳（转换为数字类型）
local window = tonumber(ARGV[3]) -- 时间窗口大小（转换为数字类型）

-- 从Redis获取当前计数器的值
local current = redis.call('GET', key)

if current == false then
    -- 情况1：计数器不存在（第一次请求或计数器已过期）
    -- 初始化计数器为1，并设置过期时间
    -- SET key value EX seconds - 设置键值对并指定过期时间（秒）
    redis.call('SET', key, 1, 'EX', window)
    -- 返回1表示请求允许
    return 1
else
    -- 情况2：计数器已存在
    -- 将字符串类型的计数器值转换为数字
    current = tonumber(current)
    
    if current < limit then
        -- 情况2a：当前请求数未达到限制
        -- INCR key - 将计数器值增加1
        redis.call('INCR', key)
        -- 返回1表示请求允许
        return 1
    else
        -- 情况2b：当前请求数已达到或超过限制
        -- 不增加计数器，直接拒绝请求
        -- 返回0表示请求拒绝
        return 0
    end
end
